@pytest.mark.db
async def test_succeeded_jobs_are_removed_sooner_than_failed_ones(
    queue_database: DatabaseSettings, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(
        "app.worker.get_settings",
        lambda: Settings(
            worker=WorkerSettings(job_retention_hours=24, failed_job_retention_hours=72)
        ),
    )
    async with app.open_async():
        jobs = {
            (status, hours): await record.defer_async(item_id=f"{status}-{hours}")
            for status, hours in (
                ("succeeded", 2),
                ("succeeded", 30),
                ("failed", 30),
                ("failed", 80),
                ("todo", 80),
            )
        }
    for (status, hours), job_id in jobs.items():
        await _execute(
            f"UPDATE procrastinate_jobs SET status = '{status}' WHERE id = {int(job_id)}"
        )
        await _execute(
            f"UPDATE procrastinate_events SET at = now() - interval '{hours} hours' "
            f"WHERE job_id = {int(job_id)}"
        )

    async with app.open_async():
        await remove_old_jobs(SimpleNamespace(app=app), timestamp=0)  # type: ignore[arg-type]

    left = {row[0] for row in await _execute("SELECT id FROM procrastinate_jobs")}
    assert left == {jobs[("succeeded", 2)], jobs[("failed", 30)], jobs[("todo", 80)]}



@pytest.mark.db
async def test_worker_process_runs_task_and_stops_on_sigterm(
    queue_database: DatabaseSettings,
) -> None:
    async with app.open_async():
        job_id = await remove_old_jobs.defer_async(timestamp=0)

    env = {
        **os.environ,
        "OLLAMAIL_DATABASE_URL": queue_database.url.get_secret_value(),
        "OLLAMAIL_LOG_FORMAT": "json",
    }
    process = await asyncio.create_subprocess_exec(
        sys.executable,
        "-m",
        "app.worker",
        cwd=Path(BACKEND_DIR),
        env=env,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
    )
    try:
        await _wait_for_status(job_id, "succeeded")
        assert await _execute("SELECT count(*) FROM procrastinate_workers") == [(2,)]

        process.send_signal(signal.SIGTERM)
        output, _ = await asyncio.wait_for(process.communicate(), timeout=20)
    finally:
        if process.returncode is None:
            process.kill()
            await process.wait()

    assert process.returncode == 0
    events = [json.loads(line)["event"] for line in output.decode().splitlines()]
    assert events[-1] == "worker_stopped"
    # Graceful shutdown unregisters the workers.
    assert await _execute("SELECT count(*) FROM procrastinate_workers") == [(0,)]


@pytest.mark.db
async def test_autogenerate_ignores_procrastinate_tables(migrated_database: str) -> None:
    # Without the filter in migrations/env.py autogenerate would drop the job tables.
    # Other test modules register test-only models, so only Procrastinate diffs count.
    try:
        await asyncio.to_thread(command.check, alembic_config(migrated_database))
    except AutogenerateDiffsDetected as exc:
        assert "procrastinate" not in str(exc)

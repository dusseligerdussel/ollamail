@pytest.mark.db
async def test_worker_runs_deferred_task(queue_database: DatabaseSettings) -> None:
    executed.clear()
    async with app.open_async():
        job_id = await record.defer_async(item_id="item-1")

    stop = asyncio.Event()
    settings = Settings(database=queue_database, worker=WorkerSettings(queues=["sync"]))
    worker = asyncio.create_task(run(settings, stop))
    try:
        await _wait_for_status(job_id, "succeeded")
    finally:
        stop.set()
        await asyncio.wait_for(worker, timeout=10)

    assert executed == ["item-1"]



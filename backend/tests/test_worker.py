async def _execute(statement: str) -> list[tuple[object, ...]]:
    engine = create_async_engine(TEST_DATABASE_URL, poolclass=NullPool)
    async with engine.begin() as connection:
        result = await connection.execute(text(statement))
        rows = [tuple(row) for row in result] if result.returns_rows else []
    await engine.dispose()
    return rows


async def _job_status(job_id: int) -> str:
    rows = await _execute(f"SELECT status FROM procrastinate_jobs WHERE id = {int(job_id)}")
    return str(rows[0][0])


async def _wait_for_status(job_id: int, status: str) -> None:
    for _ in range(200):
        if await _job_status(job_id) == status:
            return
        await asyncio.sleep(0.1)
    raise AssertionError(f"job {job_id} did not reach {status!r}")



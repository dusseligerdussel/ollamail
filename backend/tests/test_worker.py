def test_procrastinate_logs_hide_task_arguments() -> None:
    stream = io.StringIO()
    configure_logging(LoggingSettings(level="DEBUG", format="json"), stream=stream)
    logging.getLogger("procrastinate.worker").info(
        "Job %s succeeded",
        "record[1](item_id='Quarterly numbers')",
        extra={
            "action": "job_success",
            "job": {
                "id": 1,
                "task_name": "tests.record",
                "task_kwargs": {"item_id": "Quarterly numbers"},
                "call_string": "record[1](item_id='Quarterly numbers')",
            },
            "result": "Quarterly numbers",
        },
    )

    output = stream.getvalue()
    assert "Quarterly numbers" not in output
    entry = json.loads(output)
    assert entry["event"] == "job_success"
    assert entry["job"] == {"id": 1, "task_name": "tests.record"}


